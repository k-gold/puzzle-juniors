// Vite plugin that writes dist/sw.js, a small service worker that lets the site work offline.
//
// It is generated at build time because the built file names change with every build. The
// worker saves every built file the first time the site loads, then serves from that copy.
// Page loads still try the network first, so players get new versions as soon as they are
// online. Each build has its own cache name (the time it was built), and old ones are deleted.
// Files that are not part of the build output but are needed offline
const EXTRA_FILES = [
  '/',
  '/words.txt',
  '/manifest.webmanifest',
  '/favicon.svg',
  '/favicon-32.png',
  '/icons/icon-192.png',
  '/icons/icon-512.png',
  '/icons/apple-touch-icon.png',
  '/icons/spelling-bee.png',
  '/icons/word-search.png',
  '/icons/wordle.png',
  '/icons/scramble.png',
  '/icons/crossword.png',
  '/icons/store.png',
];

export function buildServiceWorker(files, version) {
  return `// GENERATED by scripts/precache-plugin.mjs at build time.
const CACHE = 'puzzle-juniors-${version}';
const FILES = ${JSON.stringify(files, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(FILES))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) => Promise.all(names.filter((n) => n !== CACHE).map((n) => caches.delete(n))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    // Pages: newest version when online, saved copy when not
    event.respondWith(
      fetch(request).catch(() => caches.match('/').then((saved) => saved || Response.error())),
    );
    return;
  }

  // Everything else: the saved copy first
  event.respondWith(
    caches.match(request).then((saved) => saved || fetch(request)),
  );
});
`;
}

export function precacheServiceWorker() {
  return {
    name: 'precache-service-worker',
    apply: 'build',
    generateBundle(options, bundle) {
      const built = Object.keys(bundle).map((name) => '/' + name);
      const files = [...new Set([...EXTRA_FILES, ...built])].sort();
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: buildServiceWorker(files, Date.now().toString(36)),
      });
    },
  };
}
